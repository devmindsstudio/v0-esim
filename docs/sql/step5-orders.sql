-- ============================================================================
-- Step 5: Booking flow — place an order (demo), atomically.
-- Run this ONCE in the Supabase SQL Editor. Safe to re-run.
--
-- One transaction does everything so it's all-or-nothing:
--   1. lock the buyer's wallet
--   2. verify the customer belongs to this distributor
--   3. check sufficient balance
--   4. create the order (status 'fulfilled', payment_ref 'DEMO')
--   5. debit the wallet + write a 'debit' ledger row linked to the order
--   6. issue the eSIM (number + QR payload), delivered 'onscreen'
-- The eSIM credentials are generated by the server and passed in (in Real Mode
-- they will come from eTijwaal instead).
-- ============================================================================
create or replace function public.place_order(
  p_distributor_id  uuid,
  p_customer_id     uuid,
  p_package_id      bigint,
  p_package_title   text,
  p_currency        text,
  p_price           numeric,
  p_esim_number     text,
  p_iccid           text,
  p_qr_payload      text,
  p_activation_code text
)
returns json
language plpgsql
as $$
declare
  v_wallet_id   uuid;
  v_tenant_id   uuid;
  v_balance     numeric;
  v_new_balance numeric;
  v_order_id    uuid;
  v_esim_id     uuid;
  v_cust        int;
begin
  if p_price is null or p_price <= 0 then
    raise exception 'Invalid package price';
  end if;
  if p_price > 1000000 then
    raise exception 'Price exceeds the maximum allowed';
  end if;

  -- Lock the buyer's wallet so the balance can't change under us.
  select id, tenant_id, balance
    into v_wallet_id, v_tenant_id, v_balance
    from public.wallets
    where distributor_id = p_distributor_id
    for update;
  if v_wallet_id is null then
    raise exception 'Wallet not found';
  end if;

  -- The customer must belong to THIS distributor.
  select 1 into v_cust
    from public.customers
    where id = p_customer_id and distributor_id = p_distributor_id;
  if v_cust is null then
    raise exception 'Customer does not belong to this distributor';
  end if;

  if v_balance < p_price then
    raise exception 'Insufficient balance';
  end if;

  v_new_balance := v_balance - p_price;

  -- 1) Order (demo: fulfilled + DEMO payment ref, quantity 1)
  insert into public.orders
    (tenant_id, distributor_id, customer_id, package_id, package_title,
     currency, unit_price, quantity, total, status, payment_ref)
  values
    (v_tenant_id, p_distributor_id, p_customer_id, p_package_id, p_package_title,
     p_currency, p_price, 1, p_price, 'fulfilled', 'DEMO')
  returning id into v_order_id;

  -- 2) Debit the wallet + ledger row linked to the order
  update public.wallets
    set balance = v_new_balance, updated_at = now()
    where id = v_wallet_id;

  insert into public.wallet_transactions
    (tenant_id, wallet_id, type, amount, balance_after, reference_order_id, note)
  values
    (v_tenant_id, v_wallet_id, 'debit', p_price, v_new_balance, v_order_id,
     'Order: ' || p_package_title);

  -- 3) Issue the eSIM
  insert into public.esims
    (order_id, iccid, esim_number, qr_payload, activation_code, status, delivered_via)
  values
    (v_order_id, p_iccid, p_esim_number, p_qr_payload, p_activation_code, 'issued', 'onscreen')
  returning id into v_esim_id;

  return json_build_object(
    'orderId', v_order_id,
    'esimId', v_esim_id,
    'total', p_price,
    'walletBalance', v_new_balance
  );
end;
$$;

-- Only the server (service_role) may place orders / move money.
revoke all on function public.place_order(uuid, uuid, bigint, text, text, numeric, text, text, text, text) from public, anon, authenticated;
grant execute on function public.place_order(uuid, uuid, bigint, text, text, numeric, text, text, text, text) to service_role;
